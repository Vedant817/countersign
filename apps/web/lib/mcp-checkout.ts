import 'server-only'

/**
 * `submit_checkout` and `get_order_status`, composed — the call sites `packages/gate` needs to be a
 * control rather than a library.
 *
 * ## What this file is
 *
 * It runs the twelve-check Gate for one merchant MCP submission and **persists the decision**. That is
 * all it does, and the two halves are both load-bearing:
 *
 *  - Running the Gate is what makes `submit_checkout` a purchase endpoint rather than a stub. The route
 *    used to answer `CS_INTERNAL` for every call (D-048: "persisted merchant payment runtime is
 *    unavailable"), which meant the agent had nothing to demonstrate and I-1 was unenforced on the
 *    reachable endpoint.
 *  - Persisting is what makes the answer *auditable*. `orchestratorStoreFromRepos().decide` writes
 *    `gate_decisions` and links it to the attempt in one transaction; a BLOCK that is not recorded is a
 *    refusal nobody can review afterwards. That writer already existed with no caller — this is the caller.
 *
 * ## What it deliberately does not do
 *
 * **It does not create a PayPal order.** An `ALLOW` here is a permission, not a transaction, and the
 * order path needs a vaulted buyer (`payment_source.paypal.vault_id`) which this deployment does not have
 * yet — HUMAN_TODO item 2. The response says so explicitly (`order_pending: true` and a sentence naming
 * what is missing) rather than leaving a caller to infer it from a null id, because "allowed" and
 * "bought" are the two facts this whole project exists to keep apart. The order path is P0-4's, and
 * `packages/orders.createOrderFromDecision` is where it will land.
 *
 * ## Why the composition lives here and not in `packages/gate`
 *
 * Same reason as `gate-runtime.ts`: the Gate must not import a database driver, a vi client or an order
 * store (`packages/gate`'s ESLint rules ban the model; the dependency direction bans the rest). This file
 * is the app's composition root, and it is the *only* place a submission turns into a decision.
 */
import {
  csError,
  newId,
  systemClock,
  type AgentId,
  type AttemptId,
  type CheckoutId,
  type CsError,
  type MandateId,
  type OrderId,
  type Result,
} from '@countersign/core'
import * as repository from '@countersign/db'
import { evaluate, type GateCheck, type GateDecision } from '@countersign/gate'
import { orchestratorStoreFromRepos } from '@countersign/orchestrator'

import { gateRuntime } from './gate-runtime'

/** What the merchant MCP's `submit_checkout` answers. Mirrors §8.9 plus two honesty fields. */
export interface CheckoutSubmission {
  readonly status: 'ALLOWED' | 'BLOCKED' | 'REVIEW'
  readonly decision_id: string | null
  readonly reasons: readonly {
    readonly code: string
    readonly message: string
    readonly userMessage: string
  }[]
  readonly checks: readonly GateCheck[]
  /** Always `null` today: order creation needs the vaulted-buyer runtime. Present so the field cannot drift. */
  readonly order_id: string | null
  /** `true` when the Gate allowed the purchase and the order path is not composed on this deployment. */
  readonly order_pending: boolean
  /** A sentence for a human, naming what happens next. Never a substitute for `status`. */
  readonly message: string
  readonly amount_minor: string | null
  readonly currency: string | null
  readonly payee: string | null
  readonly attempt_id: string
  /** UTC epoch seconds (spec §0 rule 10). */
  readonly decided_at_epoch_sec: number
}

export interface CheckoutSubmissionInput {
  readonly checkoutId: string
  readonly mandateId: string
  readonly agentId: string
  readonly l3a: string
  readonly l3b: string
}

/**
 * Evaluate one submission and record the decision.
 *
 * Returns `Result` rather than throwing (AGENTS.md rule 3): a missing `GATE_SIGNING_KEY` is a
 * configuration answer, not a stack trace, and the caller is an MCP tool handler that has to put
 * *something* on the wire.
 */
export async function submitCheckout(
  input: CheckoutSubmissionInput,
): Promise<Result<CheckoutSubmission, CsError>> {
  const runtime = await gateRuntime()
  if (!runtime.ok) return runtime

  // The merchant's own price lock is the display source for the amount. The Gate re-reads the same row for
  // check 6, so a disagreement is caught there rather than papered over here.
  const session = await repository.requireCheckoutSession(input.checkoutId as CheckoutId)
  if (!session.ok) return session

  // A fresh attempt id per submission. Replay is caught by the Gate itself (check 7, on the L3 `jti`), not
  // here: an id generated by the caller must never be what prevents a double charge, because a retry
  // generates a new one.
  const attemptId = newId('att') as AttemptId

  const decided = await evaluate(
    {
      attemptId,
      mandateId: input.mandateId as MandateId,
      checkoutId: input.checkoutId as CheckoutId,
      agentId: input.agentId as AgentId,
      l3a: input.l3a,
      l3b: input.l3b,
    },
    runtime.value,
  )
  if (!decided.ok) return decided

  const decision: GateDecision = decided.value
  const decidedAt = systemClock.nowSec()

  const recorded = await orchestratorStoreFromRepos().decide({
    decision,
    attemptId,
    at: new Date(decidedAt * 1000),
  })
  if (!recorded.ok) return recorded

  return {
    ok: true,
    value: {
      status: wireStatus(decision.decision),
      decision_id: decision.id,
      reasons: decision.reasons.map((reason) => ({
        code: reason.code,
        message: reason.message,
        userMessage: reason.userMessage,
      })),
      checks: decision.checks,
      order_id: null,
      order_pending: decision.decision === 'ALLOW',
      message: messageFor(decision),
      amount_minor: session.value.total_minor.toString(),
      currency: session.value.currency,
      payee: session.value.merchant_id,
      attempt_id: attemptId,
      decided_at_epoch_sec: decidedAt,
    },
  }
}

/**
 * The Gate's vocabulary, on §8.9's wire.
 *
 * The Gate says `ALLOW`/`BLOCK`; §8.9's `submit_checkout` contract says `ALLOWED`/`BLOCKED`. Translating
 * in one place makes the difference a decision rather than a coincidence — and the alternative, renaming
 * one side to match the other, would either change a signed decision record or change a published wire
 * contract, both of which are worse than one `switch`.
 */
function wireStatus(outcome: GateDecision['decision']): 'ALLOWED' | 'BLOCKED' | 'REVIEW' {
  if (outcome === 'ALLOW') return 'ALLOWED'
  if (outcome === 'BLOCK') return 'BLOCKED'
  return 'REVIEW'
}

