export interface OrderStatusView {
  readonly order_id: string
  readonly status: string
  readonly paypal_order_id: string
  readonly amount_minor: string
  readonly currency: string
  readonly intent: string
  readonly created_at: string
}

/**
 * Read one order from the merchant's own table.
 *
 * Deliberately a database read and **not** a PayPal call: the merchant's record is what the merchant
 * decided and recorded, and a route that re-fetched from PayPal could report a state the reconciler has
 * not yet written — two answers for one order, which is the drift `wh.process` exists to prevent (§8.12).
 */
export async function readOrderStatus(orderId: string): Promise<Result<OrderStatusView, CsError>> {
  const found = await repository.findOrderById(orderId as OrderId)
  if (!found.ok) return found
  const row = found.value
  if (row === undefined) {
    return { ok: false, error: csError('CS_NOT_FOUND', `No order ${orderId}.`) }
  }
  return {
    ok: true,
    value: {
      order_id: row.id,
      status: row.status,
      paypal_order_id: row.paypal_order_id,
      amount_minor: row.amount_minor.toString(),
      currency: row.currency,
      intent: row.intent,
      created_at: row.created_at.toISOString(),
    },
  }
}

/**
 * The sentence a buyer reads when the Gate answers.
 *
 * A `BLOCK` always names the Gate's own `userMessage` — the registry's wording, not a paraphrase — so the
 * UI cannot drift from the reason the Gate recorded. An `ALLOW` is described as what it is: a permission
 * with no order behind it on this deployment.
 */
function messageFor(decision: GateDecision): string {
  if (decision.decision === 'BLOCK' || decision.decision === 'REVIEW') {
    const first = decision.reasons[0]
    return first === undefined
      ? 'The purchase was refused before payment.'
      : `${first.userMessage} Nothing was charged.`
  }
  return (
    'Your mandate allowed this purchase. The order itself is created by the order orchestrator, which is ' +
    `not composed on this deployment yet, so no PayPal order exists. The permission is recorded as ${decision.id}.`
  )
}
