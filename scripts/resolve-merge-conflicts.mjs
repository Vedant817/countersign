/**
 * Resolve the three doc conflicts between the deterministic-compiler merge and fix/p0-12-ci-green.
 *
 * All three are **appended** documents, so the union is correct rather than a judgement call — except for
 * one real collision: both branches wrote a `D-055` decision record. The compiler branch landed first, so
 * its D-055 keeps the number and the ci-green record becomes D-056. Renumbering rather than dropping one
 * because both records are genuine, and two decisions sharing a number makes every future citation
 * ambiguous in a file whose whole purpose is being cited.
 *
 * `docs/EDGE_CASES.md` is generated by `pnpm test:ec`, so it is taken from the incoming branch and
 * regenerated rather than hand-merged.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'

const git = (...args) => execFileSync('git', args, { encoding: 'utf8' })

/** The incoming side of a conflicted file. */
function theirs(path) {
  return git('show', `:3:${path}`)
}

/** Split an appended section out of a conflict, dropping the markers. */
function section(text, marker) {
  const start = text.indexOf(marker)
  return start === -1 ? '' : text.slice(start)
}

// ── DECISIONS.md: HEAD keeps D-055, incoming is renumbered to D-056 ──────────────────────────────
{
  const path = 'docs/DECISIONS.md'
  const ours = git('show', `:2:${path}`)
  const incoming = theirs(path)

  const incomingRecord = section(incoming, '## D-055 - ')
  if (incomingRecord === '') {
    console.error('DECISIONS: could not find the incoming D-055 record; refusing to guess')
    process.exit(1)
  }
  const renumbered = incomingRecord.replace(/^## D-055 - /m, '## D-056 - ')

  // Drop the conflict markers from HEAD's side and append the renumbered record.
  const cleaned = ours
    .replace(/^<<<<<<< HEAD\r?\n/m, '')
    .replace(/^=======\r?\n[\s\S]*?^>>>>>>> origin\/fix\/p0-12-ci-green\r?\n/m, '')

  writeFileSync(path, `${cleaned.trimEnd()}\n\n---\n\n${renumbered.trimEnd()}\n`, 'utf8')
  console.log(`${path}: kept D-055 (compiler), renumbered the incoming record to D-056`)
}

// ── PROGRESS.md: both entries are wanted ─────────────────────────────────────────────────────────
{
  const path = 'docs/PROGRESS.md'
  const ours = git('show', `:2:${path}`)
  const incoming = theirs(path)

  const start = incoming.indexOf('<<<<<<< HEAD')
  const marker = incoming.indexOf('=======', start)
  const incomingBody = marker === -1 ? '' : incoming.slice(marker + '======='.length)
  const cleaned = incomingBody.replace(/^>>>>>>> .*\r?\n/m, '').trim()

  const oursClean = ours.replace(/^<<<<<<< HEAD\r?\n/m, '').replace(/^=======\r?\n[\s\S]*$/m, '')
  writeFileSync(path, `${oursClean.trimEnd()}\n\n${cleaned}\n`, 'utf8')
  console.log(`${path}: kept both entries`)
}

// ── EDGE_CASES.md: generated, so take the incoming copy and regenerate ───────────────────────────
{
  const path = 'docs/EDGE_CASES.md'
  writeFileSync(path, theirs(path), 'utf8')
  console.log(`${path}: took the incoming copy (regenerated by \`pnpm test:ec\`)`)
}

console.log(
  '\nremaining conflicts:',
  git('diff', '--name-only', '--diff-filter=U').trim() || '(none)',
)
console.log(
  'unmerged marker scan:',
  (readFileSync('docs/DECISIONS.md', 'utf8').match(/^<{7}|^={7}$|^>{7}/gm) ?? []).length,
  'in DECISIONS.md',
)
