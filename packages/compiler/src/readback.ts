/**
 * The read-back — the string the user signs.
 *
 * Spec **§8.8 (M8)**, WP-08. §8.8 calls it "Read-back is a template per constraint type", and the spec's
 * own three examples are the wording to match: "Spend at most **$130.00** in total", "Only at **Northwind
 * Outfitters**", "Expires **Fri 9 Oct, 11:59 PM IST**".
 *
 * ## Why this file is the most important string in the repository
 *
 * Spec **§18 question 46** puts "the user signs something they didn't understand" to the judges
 * directly. The threat is answered in one place and one place only: here. Everything upstream — the model,
 * the catalog, the prompt — produces *proposals*; this file turns them into the only text a human is asked
 * to approve, and it is generated by template rather than by a model for exactly that reason. A generated
 * read-back would make question 46 trivially true: the sentence would be as good as the model's mood.
 *
 * ## The four properties this file guarantees, and how each is enforced
 *
 * | Property | How |
 * |---|---|
 * | **Pure** — no clock, no LLM, no I/O, no locale lookup | Every branch reads only its arguments. `Date.UTC` is calendar arithmetic over explicit arguments; `Date.now()` appears nowhere. |
 * | **Total** — every one of the eight constraint types has a template | The template table is keyed by `CONSTRAINT_TYPES` and `READBACK_TEMPLATES` is checked against it in `test/readback.test.ts`. Adding a ninth type fails that test. |
 * | **Lossless** — nothing is dropped or summarised | One line per constraint, canonical order, no truncation. A merchant missing from `ctx.merchants` prints its raw id rather than being omitted. |
 * | **Stable** — same input, byte-identical output | Canonical ordering and deduplication, so a proposal whose constraint array was reordered renders identically. Pinned by snapshot tests. |
 *
 * ## Two things a naive read-back gets wrong, and what happens here instead
 *
 * **A cap nobody enforces must still be shown.** `budget`, `recurrence` and `agent_recurrence` are not
 * evaluated by the pinned library — spec **D19** moved them to the Gate. The obvious way to handle a
 * constraint you "cannot check" is to skip it, and that produces the exact disaster D19 exists to
 * prevent: a read-back that omits the total means the user signs a mandate whose cumulative exposure they
 * were never shown. All eight types are rendered, unconditionally.
 *
 * **A guess the user never made is part of what they are signing.** So the string also carries the
 * compiler's assumptions and, separately, its non-binding interpretation of the intent. Both are derived
 * from the compiled mandate, so they cannot disagree with the constraints above them.
 */

import {
  formatIstHuman,
  formatMoney,
  toIstParts,
  type Currency,
  type Money,
} from '@countersign/core'

import {
  constraintOfType,
  type ConstraintType,
  type Frequency,
  type MatchMode,
  type VIConstraint,
} from './constraints'
import type { Ambiguity, CompiledMandate, CompiledPreferences } from './types'

/** The only zone this surface renders in. Spec §0 rule 10: IST only in the UI. */
export type ReadBackTz = 'Asia/Kolkata'

export interface ReadBackContext {
  /** Merchant id → display name. Supplied by the caller so this file never reaches for a database. */
  readonly merchants: Readonly<Record<string, string>>
  readonly tz: ReadBackTz
}

/** The fixed first line. Present so the string still reads correctly when quoted out of context. */
export const READBACK_HEADER = '**What you are authorising**'

/** Heading for the section that carries assumptions and interpretations. */
export const READBACK_INTERPRETATION_HEADER = '**How we read your request**'

/** Heading for the section that states what the mandate does *not* do. */
export const READBACK_NOT_COVERED_HEADER = '**Not covered**'

/** Shown in place of an amount that the text never specified. */
export const NOT_SPECIFIED = 'not specified'

/** Shown in place of a date the text never specified. */
export const NO_DATE = 'no date'

// ---------------------------------------------------------------------------
// Rendering primitives
// ---------------------------------------------------------------------------

const MONTH_ABBREVIATIONS = [
  'Jan',
  'Feb',
  'Mar',
  'Apr',
  'May',
  'Jun',
  'Jul',
  'Aug',
  'Sep',
  'Oct',
  'Nov',
  'Dec',
] as const

/**
 * `YYYY-MM-DD` → `"Thu 1 Oct 2026"`, in the requested zone.
 *
 * The weekday and the calendar fields come from `core.toIstParts`, so they cannot drift from the weekday
 * `core.formatIstHuman` prints in the very next line of the same read-back.
 * `test/readback.test.ts` pins that agreement across all twelve months, because a read-back that says
 * "Thu 1 Oct" on one line and "Fri 1 Oct" on another is the kind of bug nobody catches in review and
 * every judge does.
 */
export function formatIstCalendarDate(isoDate: string, tz: ReadBackTz): string {
  switch (tz) {
    case 'Asia/Kolkata': {
      const [y = '0', mo = '0', d = '0'] = isoDate.split('-')
      // UTC midnight plus 5:30 lands on the same calendar date in IST, so the fields round-trip.
      const parts = toIstParts(Date.UTC(Number(y), Number(mo) - 1, Number(d)))
      return `${parts.weekday} ${Number(parts.day)} ${MONTH_ABBREVIATIONS[Number(parts.month) - 1]} ${parts.year}`
    }
  }
}

/**
 * Frequency codes in words a buyer would use.
 *
 * The ISO 20022 codes are precise and unreadable, and a read-back is read by a person. `SEMI` is the
 * awkward one: it means twice a month, which no single word expresses.
 */
const FREQUENCY_WORDS: Readonly<Record<Frequency, string>> = {
  INDA: 'once',
  DAIL: 'daily',
  WEEK: 'weekly',
  TWOK: 'every two weeks',
  TWMN: 'every two months',
  MNTH: 'monthly',
  TOMN: 'every three months',
  QUTR: 'quarterly',
  FOMN: 'every four months',
  SEMI: 'twice a month',
  YEAR: 'yearly',
  TYEA: 'every two years',
}

/** `"A, B or C"` — or a lone `"A"` for a one-element list. */
export function joinWithOr(items: readonly string[]): string {
  if (items.length <= 1) return items[0] ?? ''
  if (items.length === 2) return `${items[0]} or ${items[1]}`
  return `${items.slice(0, -1).join(', ')} or ${items[items.length - 1]}`
}

/**
 * `"A, B and C"` — the conjunction form, for a list of things the reader must take together
 * (currencies, assumptions) rather than choose between.
 *
 * `"A and B and C"` is what a bare `join(' and ')` produces, and it reads as a grammatical slip in
 * exactly the sentence a user is asked to trust: the ambiguity question that blocks them from signing.
 * Small, but the fix costs nothing and the wobble is in the one place the product cannot afford one.
 */
export function joinWithAnd(items: readonly string[]): string {
  if (items.length <= 1) return items[0] ?? ''
  if (items.length === 2) return `${items[0]} and ${items[1]}`
  return `${items.slice(0, -1).join(', ')} and ${items[items.length - 1]}`
}

/** A money value, bolded, or `NOT_SPECIFIED` when the constraint left it open. */
function amountText(minor: bigint | undefined, currency: Currency): string {
  if (minor === undefined) return `**${NOT_SPECIFIED}**`
  const m: Money = { minor, currency }
  return `**${formatMoney(m)}**`
}

/** Lower bound / upper bound rendered as one clause, whichever are present. */
function boundsText(
  min: bigint | undefined,
  max: bigint | undefined,
  currency: Currency,
  between: string,
  atMost: string,
  atLeast: string,
): string {
  if (min !== undefined && max !== undefined) {
    return `${between} ${amountText(min, currency)} and ${amountText(max, currency)}`
  }
  if (max !== undefined) return `${atMost} ${amountText(max, currency)}`
  if (min !== undefined) return `${atLeast} ${amountText(min, currency)}`
  return `${between} **${NOT_SPECIFIED}** and **${NOT_SPECIFIED}**`
}

/**
 * A merchant's display name, or its raw id when the caller did not supply one.
 *
 * Falling back to the id is deliberate. The obvious alternative — omit the merchant — is a security bug:
 * a line reading "Only at **Northwind Outfitters**" would then be true of a constraint that also allows
 * Contoso, and the user would sign a read-back that understates their own mandate. An ugly id is visible;
 * a silently dropped constraint is not. `test/readback.test.ts` pins this.
 */
function merchantName(id: string, ctx: ReadBackContext): string {
  return ctx.merchants[id] ?? id
}

// ---------------------------------------------------------------------------
// The eight templates
// ---------------------------------------------------------------------------

/**
 * One line per constraint type. Keyed by the type tag, exhaustive over {@link CONSTRAINT_TYPES}.
 *
 * A function rather than a template string because the money and the dates must go through
 * `formatMoney` and `formatIstHuman` (spec §8.8: "Amounts are formatted from minor units"). A template
 * literal would mean either `toFixed`, a division, or `${max / 100}` — all three are float money, which is
 * EC-FX-5's failure mode wearing a different hat.
 */
export type ReadBackTemplate = {
  /** The constraint type this template renders. Enforced against `CONSTRAINT_TYPES` in tests. */
  readonly type: ConstraintType
  /**
   * Whether this is one of the three constraints the Gate, not the library, enforces (spec D19).
   *
   * Not cosmetic: it is why the header for a mandate made only of these constraints says
   * "Countersign checks this on every payment" rather than the silent default. A cap that is checked
   * somewhere the user does not see deserves a sentence saying so.
   */
  readonly networkEnforced: boolean
  /** Render the constraint, or `null` to add no line. `null` is only for degenerate-but-valid shapes. */
  readonly render: (c: VIConstraint, ctx: ReadBackContext) => string | null
}

const ALLOWED_MERCHANTS = 'mandate.checkout.allowed_merchants'
const LINE_ITEMS = 'mandate.checkout.line_items'
const ALLOWED_PAYEES = 'mandate.payment.allowed_payees'
const AMOUNT_RANGE = 'mandate.payment.amount_range'
const BUDGET = 'mandate.payment.budget'
const RECURRENCE = 'mandate.payment.recurrence'
const AGENT_RECURRENCE = 'mandate.payment.agent_recurrence'
const REFERENCE = 'mandate.payment.reference'

export const READBACK_TEMPLATES: readonly ReadBackTemplate[] = [
  {
    type: ALLOWED_MERCHANTS,
    networkEnforced: false,
    render: (c, ctx) =>
      c.type !== ALLOWED_MERCHANTS
        ? null
        : `Only at ${c.allowed.map((m) => `**${merchantName(m.id, ctx)}**`).join(', ')}`,
  },
  {
    type: LINE_ITEMS,
    networkEnforced: false,
    render: (c, _ctx) => {
      if (c.type !== LINE_ITEMS) return null
      const how: Readonly<Record<MatchMode, string>> = {
        minimum: 'at least',
        exact: 'exactly',
      }
      return c.items
        .map(
          (line) =>
            `Buy ${how[c.match_mode]} **${line.quantity}** of ${line.acceptable_items
              .map((item) => `**${item.title}**`)
              .join(' or ')}`,
        )
        .join('\n')
    },
  },
  {
    type: ALLOWED_PAYEES,
    networkEnforced: false,
    render: (c, ctx) =>
      c.type !== ALLOWED_PAYEES
        ? null
        : `Pay only ${c.allowed.map((m) => `**${merchantName(m.id, ctx)}**`).join(', ')}`,
  },
  {
    type: AMOUNT_RANGE,
    networkEnforced: false,
    render: (c) =>
      c.type !== AMOUNT_RANGE
        ? null
        : `${boundsText(c.min, c.max, c.currency, 'Spend between', 'Spend at most', 'Spend at least')} per payment`,
  },
  {
    type: BUDGET,
    networkEnforced: true,
    render: (c) =>
      c.type !== BUDGET
        ? null
        : `${boundsText(c.min, c.max, c.currency, 'Spend between', 'Spend at most', 'Spend at least')} in total`,
  },
  {
    type: RECURRENCE,
    networkEnforced: true,
    render: (c, ctx) => {
      if (c.type !== RECURRENCE) return null
      const parts = [
        `Payments repeat **${FREQUENCY_WORDS[c.frequency]}**`,
        `from **${formatIstCalendarDate(c.start_date, ctx.tz)}**`,
      ]
      if (c.end_date !== undefined)
        parts.push(`until **${formatIstCalendarDate(c.end_date, ctx.tz)}**`)
      let line = parts.join(' ')
      if (c.number !== undefined) line += `, up to **${c.number}** times`
      return line
    },
  },
  {
    type: AGENT_RECURRENCE,
    networkEnforced: true,
    render: (c, ctx) => {
      if (c.type !== AGENT_RECURRENCE) return null
      let line = [
        `The agent may pay **${FREQUENCY_WORDS[c.frequency]}**`,
        `from **${formatIstCalendarDate(c.start_date, ctx.tz)}**`,
        `until **${formatIstCalendarDate(c.end_date, ctx.tz)}**`,
      ].join(' ')
      if (c.max_occurrences !== undefined) line += `, at most **${c.max_occurrences}** times`
      return line
    },
  },
  {
    type: REFERENCE,
    networkEnforced: false,
    render: (c) =>
      c.type !== REFERENCE ? null : 'This mandate is linked to every payment it authorises',
  },
]

