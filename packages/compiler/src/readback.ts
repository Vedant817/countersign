/**
 * The order lines appear in, which is **not** the library's type order.
 *
 * §8.8's three read-back examples appear in this order — "Spend at most **$130.00** in total", "Only at
 * **Northwind Outfitters**", "Expires …" — and that is the order a reader wants: the total cap first,
 * because it is the number that decides whether this mandate is safe, then who the money can go to, then
 * what it can buy, then when it repeats, then when it dies.
 *
 * Deliberately distinct from `CONSTRAINT_TYPES`, which is the order `constraint_shapes.json` happens to be
 * keyed in and therefore an order of *no* editorial meaning. Keeping the two separate means reordering
 * the fixture cannot silently reorder a sentence a buyer reads.
 */
export const READBACK_ORDER: readonly ConstraintType[] = [
  BUDGET,
  AMOUNT_RANGE,
  ALLOWED_MERCHANTS,
  ALLOWED_PAYEES,
  LINE_ITEMS,
  RECURRENCE,
  AGENT_RECURRENCE,
  REFERENCE,
]

/** Canonical order: one line per type, in `READBACK_ORDER`, whatever order the array arrived in. */
function canonicalConstraints(constraints: readonly VIConstraint[]): VIConstraint[] {
  const byType = new Map<ConstraintType, VIConstraint>()
  for (const c of constraints) if (!byType.has(c.type)) byType.set(c.type, c)
  const out: VIConstraint[] = []
  for (const type of READBACK_ORDER) {
    const c = byType.get(type)
    if (c !== undefined) out.push(c)
  }
  return out
}

/** One line per assumption, deduplicated, in the order given. */
function assumptionLines(assumptions: readonly string[]): string[] {
  const out: string[] = []
  for (const a of assumptions) {
    const trimmed = a.trim()
    if (trimmed.length > 0 && !out.includes(trimmed)) out.push(trimmed)
  }
  return out
}

/**
 * `"size"` / `"colour"` / `"model"` / `"notes"` → the sentence that says it grants nothing.
 *
 * Note the key/label split. §8.8's `preferences` field is spelled `color` (matching the catalog attribute
 * vocabulary the spec uses elsewhere), while the sentence a buyer reads is spelled `colour`. The two are
 * deliberately not unified: the field name is an API contract, the label is prose.
 */
const PREFERENCE_LABELS: ReadonlyArray<readonly [keyof CompiledPreferences, string]> = [
  ['size', 'size'],
  ['color', 'colour'],
  ['model', 'model'],
  ['notes', 'notes'],
]

/**
 * The line that tells the user a preference is not a limit.
 *
 * §8.8 is explicit that `preferences` is "**NOT** a VI constraint". So it cannot be rendered like one, and
 * it cannot be omitted either — an agent that suddenly starts buying size M shoes has to have come from
 * somewhere the user was told about. One sentence, naming what was inferred and what it does not do.
 */
export function preferenceLines(preferences: CompiledPreferences): string[] {
  const found = PREFERENCE_LABELS.filter(([key]) => {
    const v = preferences[key]
    return typeof v === 'string' && v.trim().length > 0
  })
  if (found.length === 0) return []
  const quoted = found.map(([key, label]) => `**${label}** "${String(preferences[key]).trim()}"`)
  const list =
    quoted.length === 1
      ? quoted[0]!
      : `${quoted.slice(0, -1).join(', ')} and ${quoted[quoted.length - 1]}`
  return [
    `We read ${list} as a preference, not a limit. These are not signed and do not bound what the agent ` +
      'may buy.',
  ]
}

/** The line that names the one thing a live mandate never does. */
export function expiryCoverageLine(): string {
  return (
    'Expiry: there is no automatic renewal. When this mandate expires the agent cannot spend under it ' +
    'again, even if it meant to.'
  )
}

/**
 * Render a compiled mandate as the plain-English text the user signs.
 *
 * **Pure.** Every value below is a function of `compiled` or `ctx`; nothing here reads a clock, calls a
 * model, loads a locale, or touches the filesystem. `Date.UTC` is calendar arithmetic on explicit
 * arguments, not a clock read (spec §0 rule 10).
 *
 * **What is in it.** A header; one line per constraint in canonical order; the assumptions the compiler
 * made and the preferences it inferred, under their own heading; and one line about expiry.
 *
 * **What is deliberately not in it.** The open questions. §8.8 says the UI must resolve every ambiguity
 * before signing, so a read-back carrying an unanswered question would be a prompt for the user to sign
 * something the compiler itself says is incomplete. `hasBlockingAmbiguities` gates the screen instead —
 * the gate is one line in the UI, and the read-back stays a statement about a finished mandate.
 *
 * @param ctx `merchants` supplies display names for merchant ids; `tz` selects the calendar rendering.
 */
export function readBack(c: CompiledMandate, ctx: ReadBackContext): string {
  const lines: string[] = [READBACK_HEADER]

  const ordered = canonicalConstraints(c.constraints)
  const networkEnforcedOnly =
    ordered.length > 0 &&
    ordered.every(
      (x) => READBACK_TEMPLATES.find((t) => t.type === x.type)?.networkEnforced === true,
    )

  for (const type of READBACK_ORDER) {
    const constraint = constraintOfType(ordered, type)
    if (constraint === null) continue
    const template = READBACK_TEMPLATES.find((t) => t.type === type)
    if (template === undefined) continue
    const rendered = template.render(constraint, ctx)
    if (rendered === null) continue
    for (const line of rendered.split('\n')) lines.push(line)
  }

  if (ordered.length === 0) {
    lines.push(
      'No spending limits are set on this mandate. The agent may spend without a cap for as long as it ' +
        'is valid.',
    )
  }

  lines.push(`This mandate expires **${formatIstHuman(c.expiresAtEpochSec)}**`)

  if (networkEnforcedOnly) {
    lines.push(
      'Countersign checks each of these limits on every payment, including the ones the payment network ' +
        'does not check itself.',
    )
  }

  const interpretation = [...assumptionLines(c.assumptions), ...preferenceLines(c.preferences)]
  if (interpretation.length > 0) {
    lines.push('')
    lines.push(READBACK_INTERPRETATION_HEADER)
    for (const line of interpretation) lines.push(`- ${line}`)
  }

  lines.push('')
  lines.push(READBACK_NOT_COVERED_HEADER)
  lines.push(`- ${expiryCoverageLine()}`)

  return lines.join('\n')
}

/**
 * The questions that must be answered before {@link readBack}'s output may be signed.
 *
 * Exported next to the renderer because the two are one decision: a read-back is a statement about a
 * finished mandate, so it is only ever rendered once these are empty. Callers that want a single check
 * should use `hasBlockingAmbiguities`; this is for a UI that renders the questions alongside the text.
 */
export function readBackPreconditions(c: CompiledMandate): Ambiguity[] {
  return c.ambiguities
}
